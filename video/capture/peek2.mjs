import { launch, signIn, clickAt } from './lib.mjs';
const OUT = process.argv[2];
const { browser, page } = await launch();
await signIn(page);
await page.waitForTimeout(1500);
const btn = page.getByRole('button', { name: /^Travel/ });
console.log('travel buttons:', await btn.count(), (await btn.allInnerTexts()).join(' | '));
const b = await btn.first().boundingBox(); console.log('box', JSON.stringify(b));
await clickAt(page, b.x + b.width / 2, b.y + b.height / 2, 650);
await page.waitForTimeout(2000);
await page.screenshot({ path: OUT + '/peek-travel.png' });
console.log('aside count', await page.locator('aside').count());
await browser.close();
